// ─── Deterministic Model Calculation Engine ─────────────────────────────────

export function calculateFinancialModel(
  scenarioId: ScenarioId = 'base',
  customAssumptions?: Partial<ScenarioAssumptions>,
  customPricing: PlanPricing = RUNSTEAD_INDICATIVE_PRICING
): FinancialModelResults {
  const baseAssumptions = SCENARIO_ASSUMPTIONS[scenarioId];
  const assumptions: ScenarioAssumptions = {
    ...baseAssumptions,
    ...(customAssumptions || {}),
    tierDistribution: {
      ...baseAssumptions.tierDistribution,
      ...(customAssumptions?.tierDistribution || {}),
    },
  };

  const pricing = customPricing;
  const records: MonthlyFinancialRecord[] = [];

  let currentFreeTenants = 0;
  let activeLaunch = 0;
  let activeGrowth = 0;
  let activeScale = 0;
  let activeEnterprise = 0;
  let cumulativeCashFlow = 0;

  let breakEvenMonth: number | null = null;
  let paybackMonth: number | null = null;
  let maxDeficit = 0;

  for (let m = 1; m <= 36; m++) {
    // 1. Inflow of Free Sandbox Resellers
    const monthlyNewFree = Math.round(
      assumptions.initialMonthlyFreeTenants * Math.pow(1 + assumptions.monthlyFreeGrowthRate, m - 1)
    );
    currentFreeTenants += monthlyNewFree;

    // 2. Inflow of New Paying Resellers (Conversions + Direct)
    const convertedFromFree = Math.round(monthlyNewFree * assumptions.freeToPaidConversionRate);
    const directPaid = Math.round(
      assumptions.directPaidSignupsInitial * Math.pow(1 + assumptions.directPaidGrowthRate, m - 1)
    );
    const totalNewPaid = convertedFromFree + directPaid;

    // 3. Distribution Across Tiers
    const newLaunch = Math.round(totalNewPaid * assumptions.tierDistribution.launch);
    const newGrowth = Math.round(totalNewPaid * assumptions.tierDistribution.growth);
    const newScale = Math.round(totalNewPaid * assumptions.tierDistribution.scale);
    const newEnterprise = Math.max(0, totalNewPaid - newLaunch - newGrowth - newScale);

    // 4. Churn Handling across Existing Customer Base
    const prevTotalPaying = activeLaunch + activeGrowth + activeScale + activeEnterprise;
    const churnTotal = Math.round(prevTotalPaying * assumptions.monthlyChurnRate);

    // Attribute churn proportionally
    let churnLaunch = 0;
    let churnGrowth = 0;
    let churnScale = 0;
    let churnEnterprise = 0;

    if (prevTotalPaying > 0) {
      churnLaunch = Math.min(activeLaunch, Math.round(churnTotal * (activeLaunch / prevTotalPaying)));
      churnGrowth = Math.min(activeGrowth, Math.round(churnTotal * (activeGrowth / prevTotalPaying)));
      churnScale = Math.min(activeScale, Math.round(churnTotal * (activeScale / prevTotalPaying)));
      churnEnterprise = Math.min(activeEnterprise, Math.max(0, churnTotal - churnLaunch - churnGrowth - churnScale));
    }

    // 5. Active Subscriptions at End of Month
    activeLaunch = Math.max(0, activeLaunch - churnLaunch + newLaunch);
    activeGrowth = Math.max(0, activeGrowth - churnGrowth + newGrowth);
    activeScale = Math.max(0, activeScale - churnScale + newScale);
    activeEnterprise = Math.max(0, activeEnterprise - churnEnterprise + newEnterprise);

    const totalPayingCustomers = activeLaunch + activeGrowth + activeScale + activeEnterprise;
    const actualChurned = churnLaunch + churnGrowth + churnScale + churnEnterprise;
    const retentionRate = prevTotalPaying > 0 ? 1 - actualChurned / prevTotalPaying : 1.0;

    // 6. MRR & ARR Calculations
    const mrrLaunch = activeLaunch * pricing.launch;
    const mrrGrowth = activeGrowth * pricing.growth;
    const mrrScale = activeScale * pricing.scale;
    const mrrEnterprise = activeEnterprise * pricing.enterprise;
    const totalMRR = mrrLaunch + mrrGrowth + mrrScale + mrrEnterprise;
    const totalARR = totalMRR * 12;
    const arpu = totalPayingCustomers > 0 ? Math.round((totalMRR / totalPayingCustomers) * 100) / 100 : 0;

    // 7. Cost of Goods Sold (Direct Variable Infrastructure & Transaction Costs)
    const varHosting = Math.round(totalPayingCustomers * assumptions.variableHostingCostPerCustomer);
    const paymentProc = Math.round(
      totalMRR * assumptions.paymentProcessingPercent +
      totalPayingCustomers * assumptions.paymentProcessingFixedFee
    );
    const apiOverhead = Math.round(totalPayingCustomers * assumptions.thirdPartyApiCostPerCustomer);
    const totalCOGS = varHosting + paymentProc + apiOverhead;

    const grossProfit = totalMRR - totalCOGS;
    const grossMarginPercent = totalMRR > 0 ? Math.round((grossProfit / totalMRR) * 1000) / 10 : 0;

    // 8. Fixed Operating Expenses (OpEx)
    const supportCost = Math.round(totalPayingCustomers * assumptions.supportPerPayingCustomer);
    const totalOpEx =
      assumptions.coreEngineeringMonthly +
      assumptions.baseClusterInfrastructureMonthly +
      supportCost +
      assumptions.salesAndMarketingMonthly +
      assumptions.administrativeAndGeneralMonthly;

    const totalOperatingCost = totalCOGS + totalOpEx;
    const netCashFlow = totalMRR - totalOperatingCost;
    cumulativeCashFlow += netCashFlow;

    if (cumulativeCashFlow < maxDeficit) {
      maxDeficit = cumulativeCashFlow;
    }

    const cashBalance = assumptions.illustrativeCapitalBudget + cumulativeCashFlow;

    if (netCashFlow >= 0 && breakEvenMonth === null) {
      breakEvenMonth = m;
    }
    if (cumulativeCashFlow >= 0 && paybackMonth === null) {
      paybackMonth = m;
    }

    records.push({
      month: m,
      freeSandboxTenants: currentFreeTenants,
      newPaidCustomers: totalNewPaid,
      churnedCustomers: actualChurned,
      payingCustomersByPlan: {
        launch: activeLaunch,
        growth: activeGrowth,
        scale: activeScale,
        enterprise: activeEnterprise,
      },
      totalPayingCustomers,
      retentionRate,
      mrrByPlan: {
        launch: mrrLaunch,
        growth: mrrGrowth,
        scale: mrrScale,
        enterprise: mrrEnterprise,
      },
      mrr: totalMRR,
      arr: totalARR,
      arpu,
      cogs: {
        variableHosting: varHosting,
        paymentProcessing: paymentProc,
        thirdPartyApis: apiOverhead,
        total: totalCOGS,
      },
      grossProfit,
      grossMarginPercent,
      opex: {
        coreEngineering: assumptions.coreEngineeringMonthly,
        baseInfrastructure: assumptions.baseClusterInfrastructureMonthly,
        customerSupport: supportCost,
        salesAndMarketing: assumptions.salesAndMarketingMonthly,
        administrative: assumptions.administrativeAndGeneralMonthly,
        total: totalOpEx,
      },
      totalMonthlyOperatingCost: totalOperatingCost,
      netCashFlow,
      cumulativeCashFlow,
      cashBalance,
    });
  }

  // 9. Annual Summaries (Year 1, 2, 3)
  const annualSummaries: AnnualFinancialSummary[] = [1, 2, 3].map((yr) => {
    const startIdx = (yr - 1) * 12;
    const endIdx = yr * 12;
    const yearRecords = records.slice(startIdx, endIdx);
    const endingRecord = yearRecords[yearRecords.length - 1];

    const totalAnnualRevenue = yearRecords.reduce((acc, r) => acc + r.mrr, 0);
    const totalAnnualCOGS = yearRecords.reduce((acc, r) => acc + r.cogs.total, 0);
    const annualGrossProfit = totalAnnualRevenue - totalAnnualCOGS;
    const totalAnnualOpEx = yearRecords.reduce((acc, r) => acc + r.opex.total, 0);
    const netAnnualCashFlow = totalAnnualRevenue - (totalAnnualCOGS + totalAnnualOpEx);

    return {
      year: yr,
      endingMRR: endingRecord.mrr,
      endingARR: endingRecord.arr,
      endingPayingCustomers: endingRecord.totalPayingCustomers,
      totalAnnualRevenue,
      totalAnnualCOGS,
      annualGrossProfit,
      annualGrossMarginPercent:
        totalAnnualRevenue > 0
          ? Math.round((annualGrossProfit / totalAnnualRevenue) * 1000) / 10
          : 0,
      totalAnnualOpEx,
      netAnnualCashFlow,
      blendedARPU: endingRecord.arpu,
    };
  });

  const lastMonth = records[records.length - 1];
  const totalMonthsWithRev = records.filter((r) => r.mrr > 0);
  const avgMargin =
    totalMonthsWithRev.length > 0
      ? Math.round(
          (totalMonthsWithRev.reduce((acc, r) => acc + r.grossMarginPercent, 0) /
            totalMonthsWithRev.length) *
            10
        ) / 10
      : 0;

  // Unit Economics summary (Year 3 baseline)
  const finalYearMonthlyAcquisitions = lastMonth.newPaidCustomers;
  const blendedCAC =
    finalYearMonthlyAcquisitions > 0
      ? Math.round(assumptions.salesAndMarketingMonthly / finalYearMonthlyAcquisitions)
      : 0;

  // LTV = (ARPU * Gross Margin) / Churn
  const monthlyGrossMarginDecimal = (lastMonth.grossMarginPercent || 75) / 100;
  const estimatedLTV =
    assumptions.monthlyChurnRate > 0 && lastMonth.arpu > 0
      ? Math.round((lastMonth.arpu * monthlyGrossMarginDecimal) / assumptions.monthlyChurnRate)
      : 0;

  const ltvToCacRatio = blendedCAC > 0 ? Math.round((estimatedLTV / blendedCAC) * 10) / 10 : 0;

  return {
    scenario: assumptions,
    planPricing: pricing,
    monthlyRecords: records,
    annualSummaries,
    breakEvenMonth,
    paybackMonth,
    peakFundingRequirement: Math.abs(maxDeficit),
    endingYear3ARR: lastMonth.arr,
    endingYear3Customers: lastMonth.totalPayingCustomers,
    averageGrossMarginPercent: avgMargin,
    estimatedLTV,
    blendedCAC,
    ltvToCacRatio,
  };
}
