export type ScenarioId = 'conservative' | 'base' | 'upside';

export interface TierDistribution {
  launch: number;
  growth: number;
  scale: number;
  enterprise: number;
}

export interface ScenarioAssumptions {
  id: ScenarioId;
  name: string;
  badge: string;
  tagline: string;
  description: string;

  // Reseller Acquisition
  initialMonthlyFreeTenants: number;
  monthlyFreeGrowthRate: number; // e.g. 0.04 = 4% MoM
  freeToPaidConversionRate: number; // e.g. 0.05 = 5%
  directPaidSignupsInitial: number; // organic direct paid acquisitions
  directPaidGrowthRate: number;

  // Paid Tier Mix
  tierDistribution: TierDistribution;

  // Churn & Retention
  monthlyChurnRate: number; // e.g. 0.025 = 2.5%

  // Variable Unit Economics (per active paying customer per month)
  variableHostingCostPerCustomer: number; // Dedicated tenant compute / db allocation
  paymentProcessingPercent: number; // e.g. 0.029 = 2.9%
  paymentProcessingFixedFee: number; // $0.30 per transaction
  thirdPartyApiCostPerCustomer: number; // DNS, registry lookup, ACME overhead

  // Fixed Monthly Operating Expenses (USD)
  coreEngineeringMonthly: number; // Systems & Fullstack engineer allocation
  baseClusterInfrastructureMonthly: number; // HA DB, staging, build runners
  supportPerPayingCustomer: number; // Customer support load scaling
  salesAndMarketingMonthly: number; // Developer advocacy, content, listings
  administrativeAndGeneralMonthly: number; // Compliance, legal, SaaS tools

  // Milestone Capital Allocation
  illustrativeCapitalBudget: number; // Target milestone development budget
}

export interface MonthlyFinancialRecord {
  month: number;
  
  // Customers
  freeSandboxTenants: number;
  newPaidCustomers: number;
  churnedCustomers: number;
  payingCustomersByPlan: {
    launch: number;
    growth: number;
    scale: number;
    enterprise: number;
  };
  totalPayingCustomers: number;
  retentionRate: number;

  // Revenue (USD)
  mrrByPlan: {
    launch: number;
    growth: number;
    scale: number;
    enterprise: number;
  };
  mrr: number;
  arr: number; // Annualized Recurring Revenue = MRR * 12
  arpu: number; // Average Revenue Per User

  // Operating Costs (USD)
  cogs: {
    variableHosting: number;
    paymentProcessing: number;
    thirdPartyApis: number;
    total: number;
  };
  grossProfit: number;
  grossMarginPercent: number;

  opex: {
    coreEngineering: number;
    baseInfrastructure: number;
    customerSupport: number;
    salesAndMarketing: number;
    administrative: number;
    total: number;
  };

  totalMonthlyOperatingCost: number;
  netCashFlow: number; // MRR - totalMonthlyOperatingCost
  cumulativeCashFlow: number;
  cashBalance: number;
}

export interface AnnualFinancialSummary {
  year: number;
  endingMRR: number;
  endingARR: number;
  endingPayingCustomers: number;
  totalAnnualRevenue: number;
  totalAnnualCOGS: number;
  annualGrossProfit: number;
  annualGrossMarginPercent: number;
  totalAnnualOpEx: number;
  netAnnualCashFlow: number;
  blendedARPU: number;
}

export interface FinancialModelResults {
  scenario: ScenarioAssumptions;
  planPricing: PlanPricing;
  monthlyRecords: MonthlyFinancialRecord[];
  annualSummaries: AnnualFinancialSummary[];
  breakEvenMonth: number | null; // Month where monthly net cash flow becomes >= 0
  paybackMonth: number | null;   // Month where cumulative cash flow becomes >= 0
  peakFundingRequirement: number; // Maximum negative cumulative cash flow
  endingYear3ARR: number;
  endingYear3Customers: number;
  averageGrossMarginPercent: number;
  estimatedLTV: number;
  blendedCAC: number;
  ltvToCacRatio: number;
}

